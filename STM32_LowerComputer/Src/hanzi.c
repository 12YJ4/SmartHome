//封装画空心矩形的函数,几个参数，什么类型
//x，y坐标，长、宽\颜色
//封装一个空心矩形函数
//参数1：x轴坐标  参数2：y轴坐标  参数3：长 参数4：宽  参数5:颜色
int rectangle_1(uint16_t x,uint16_t y,int l,int w,uint16_t color)
{
	int tempx = x;
	int tempy = y;
	if(x+l > 128 || y+w > 128)  return -1;
	for(tempx=x;tempx < x+l;tempx++)  //上下两条线
	{
		Gui_DrawPoint(tempx,y,color); //画上线
		Gui_DrawPoint(tempx,y+w,color); //画上线
	}
	for(tempy=y;tempy < y+w;tempy++) //左右两条线
	{
		Gui_DrawPoint(x,tempy,color); //画左线
		Gui_DrawPoint(x+l,tempy,color); //画右线
	}
	return 0;
}

int rectangle_2(uint16_t x,uint16_t y,int len,int width,uint16_t color)
{
	int tempx =x;
	int tempy =y;
	if(x+len>128 || y+width>128)
		return -1;
	for(tempy = y;tempy <= y+width;tempy++)
	{
		for(tempx = x;tempx <= x+len;tempx++)
		{
			Gui_DrawPoint(tempx,tempy,color); //画点
			//HAL_Delay(10);
		}
	}
	return 0;	
}

