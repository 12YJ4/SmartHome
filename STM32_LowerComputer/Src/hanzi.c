int show_8(uint16_t x,uint16_t y,uint16_t fc,uint16_t bc,unsigned char data)//显示8位的内容
{
	//遍历8个像素点
	int tempx=x;
	for(tempx = x;tempx<x+8;tempx++)
	{
		//第一个像素点，判断8位中的每一位是0还是1;如果是1则前景色显示黑色，0则背景色白色
		if(data & 0x80)//data & 0x10<<7
		{
			Gui_DrawPoint(tempx,y,fc);
		}
		else 
		{
			Gui_DrawPoint(tempx,y,bc);
		}
		data = data<<1;//为了判断剩下的像素点，data左移一位，每次判断结束画完后第二位自动补上
	}
	return 0;
}

//显示16*16汉字大小的函数
int show_16(uint16_t x,uint16_t y,uint16_t fc,uint16_t bc,unsigned char* p)
{
	int tempx=x,tempy=y,i=0;
	for(tempy=y;tempy<y+16;tempy++)
	{
		for(tempx=x;tempx<x+16;tempx+=8)//每8位算一个
		{
			show_8(tempx,tempy,fc,bc,p[i]);
			i++;
		}
	}
	return 0;
}
	//显示任意汉字
int show_any(uint16_t x,uint16_t y,uint16_t fc,uint16_t bc,unsigned char* p,int l,int w)
{
	int tempx=x,tempy=y+w,i=0;
	for(tempy=y;tempy<y+w;tempy++)
	{
		for(tempx=x;tempx<x+l;tempx+=8)//每8位算一个
		{
			show_8(tempx,tempy,fc,bc,p[i]);
			i++;
		}
	}
	return 0;
}

